"""Agent evaluation against REAL Gemini (CP3 approved targets + F3 targets).

Not part of the normal run. Requires GEMINI_API_KEY, GEMINI_MODEL, a validation
run (scripts/run_validation.py) and the Gemini knowledge index
(scripts/ingest_knowledge.py --provider gemini):

    pytest -m eval -v

F7a (quota-aware, harness only):
* EVAL_LLM_MIN_INTERVAL_SECONDS=13   paces every Gemini request (free tier: 5/min).
* EVAL_AGENT_REPORT=cp4_gemini_eval.json   reuses the report written by
  `scripts/evaluate_agent.py --out` (full or --case-set stratified) instead of
  calling Gemini again; the targets and the N10 check are read from it.
  Without it, the module runs the full case set (~75 requests: needs > 20/day).
* When only LLM-dependent targets miss AND the provider returned 429 / 503 /
  timeouts, those tests are skipped as INCONCLUSIVE (not an Agent quality result).
"""

import json
import os
from pathlib import Path

import pytest

from app.agent.factory import build_agent
from app.core.config import get_settings
from app.observability.events import RecordingObserver
from scripts.eval_pacing import is_transient, min_interval_from_env, paced_gemini_llm, provider_errors, shared_guard
from scripts.evaluate_agent import LLM_DEPENDENT, evaluate

pytestmark = pytest.mark.eval


def _gemini_agent(settings, observer):
    """Evaluation client: pacing (EVAL_LLM_MIN_INTERVAL_SECONDS, default 0) + quota guard (F7c)."""
    llm = paced_gemini_llm(settings, min_interval_from_env())
    return build_agent(settings, llm=llm, llm_provider="gemini", embeddings_provider="gemini", observer=observer)


@pytest.fixture(scope="module")
def report():
    saved = os.environ.get("EVAL_AGENT_REPORT", "").strip()
    if saved:
        data = json.loads(Path(saved).read_text(encoding="utf-8"))
        assert data["llm"].startswith("gemini/"), f"{saved} is not a Gemini evaluation report"
        return data
    settings = get_settings()
    if not settings.gemini_api_key or not settings.gemini_model:
        pytest.skip("GEMINI_API_KEY and GEMINI_MODEL are required for the real Agent evaluation")
    observer = RecordingObserver()
    agent = _gemini_agent(settings, observer)
    if agent.retriever is None:
        pytest.skip("Gemini knowledge index not found: run scripts/ingest_knowledge.py --provider gemini")
    if not agent.tool.available_periods():
        pytest.skip("No validation run: run scripts/run_validation.py")
    return evaluate(agent, agent.tool.results_dir, observer,
                    shared_guard([settings.gemini_api_key.get_secret_value()]))


@pytest.mark.parametrize("metric", ["routing_accuracy", "clarify_missing_employee", "out_of_scope",
                                    "agent_engine_consistency", "seeded_auditor_detection",
                                    "intent_llm_rate", "generation_success_rate"])
def test_agent_target(report, metric):
    target = report["targets"][metric]
    if not target["met"] and report.get("status") == "INCONCLUSIVE" and metric in LLM_DEPENDENT:
        pytest.skip(f"INCONCLUSIVE — provider quota/availability {report['provider_errors']}: "
                    f"{metric}={target['actual']}; rerun with EVAL_LLM_MIN_INTERVAL_SECONDS")
    assert target["met"], (metric, target, report["llm_fallbacks"], report.get("provider_errors"),
                           report["routing_failures"], report["consistency_failures"])


def test_reported_metrics_are_present(report):
    assert 0 <= report["allow_without_rewrite_rate"] <= 1
    if report.get("status") == "INCONCLUSIVE" and report["generated_answers"] == 0:
        pytest.skip(f"INCONCLUSIVE — provider quota/availability {report['provider_errors']}")
    assert report["generated_answers"] > 0, "no answer was generated by the LLM"
    assert report["latency_ms_by_route"]


def test_spanish_rag_uses_english_retrieval_query():
    """N10: with Gemini working, a Spanish policy question is searched with an English rewrite.

    With EVAL_AGENT_REPORT (F7d) the check is read from the saved report: no Gemini request.
    """
    saved = os.environ.get("EVAL_AGENT_REPORT", "").strip()
    if saved:
        check = json.loads(Path(saved).read_text(encoding="utf-8")).get("n10_check") or {}
        if not check.get("cases"):
            pytest.skip("the saved report has no Spanish RAG case for N10")
        assert check["passed"], check["cases"]
        return
    settings = get_settings()
    if not settings.gemini_api_key or not settings.gemini_model:
        pytest.skip("GEMINI_API_KEY and GEMINI_MODEL are required")
    from app.agent.contracts import AgentRequest

    observer = RecordingObserver()
    agent = _gemini_agent(settings, observer)
    if agent.retriever is None:
        pytest.skip("Gemini knowledge index not found")
    queries: list[str] = []
    original = agent._retrieve
    agent._retrieve = lambda query: (queries.append(query), original(query))[1]   # spy only

    response = agent.handle(AgentRequest("eval-n10", "¿Quién aprueba la nómina?"))
    errors = provider_errors(observer.events)
    if response.route_source != "llm_intent" and is_transient(errors):
        pytest.skip(f"INCONCLUSIVE — provider quota/availability {errors}")
    assert response.route_source == "llm_intent", (response.versions.get("llm_degraded"), errors)
    assert response.route == "RAG"
    from scripts.evaluate_agent import is_english_rewrite
    assert queries and is_english_rewrite(queries[0], "¿Quién aprueba la nómina?"), queries
    assert response.answer_mode in ("llm", "template+llm"), response.answer_mode
